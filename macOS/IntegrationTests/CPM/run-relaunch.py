# Review-only: run the owned error-6 fixture in two separate app-host processes.
import argparse
import hashlib
import json
import os
from pathlib import Path
import plistlib
import subprocess
import time
import uuid

parser = argparse.ArgumentParser()
parser.add_argument('--products', type=Path, required=True)
parser.add_argument('--output', type=Path, required=True)
parser.add_argument('--manifest', type=Path, help='Optional pre-transfer signed bundle manifest')
parser.add_argument('--plan', type=Path, help='Xcode-generated ON xctestrun; required if Products lacks P3-Acceptance-ON.xctestrun')
parser.add_argument('--flags', nargs='+', choices=['ON', 'OFF'], default=['ON', 'OFF'])
args = parser.parse_args()
products = args.products.resolve()
output = args.output.resolve()
output.mkdir(exist_ok=False, parents=True)
expected = json.loads(args.manifest.read_text()) if args.manifest else None
base_plan = args.plan or products / 'P3-Acceptance-ON.xctestrun'
assert base_plan.is_file(), 'Pass --plan with the xctestrun generated by build-for-testing'

def bundle():
    app = products / 'Debug/DuckDuckGo.app'
    result = {}
    for p in sorted(app.rglob('*')):
        rel = str(p.relative_to(app))
        if p.is_symlink():
            result[rel] = {'link': os.readlink(p)}
        elif p.is_file():
            digest = hashlib.sha256()
            with p.open('rb') as stream:
                for data in iter(lambda: stream.read(8 * 1024 * 1024), b''):
                    digest.update(data)
            result[rel] = {'sha256': digest.hexdigest(), 'mode': p.stat().st_mode & 0o777}
    assert result, 'Missing signed app/XCTest bundle'
    if expected is not None:
        assert result == expected, 'App/XCTest bundle changed'
    return result

expected = bundle()
(output / 'bundle-before.json').write_text(json.dumps(expected, sort_keys=True))
results = {}
for flag in args.flags:
    token = str(uuid.uuid4()).upper()
    previous_pid = None
    for phase in ['prepare', 'resume']:
        name = flag.lower() + '-' + phase
        plan = plistlib.loads(base_plan.read_bytes())
        target = plan['Integration Tests']
        target['OnlyTestIdentifiers'] = ['CPMStableBaseURLIntegrationTests/testBackgroundError6AcrossAppRelaunch']
        target['TestTimeoutsEnabled'] = True
        target['DefaultTestExecutionTimeAllowance'] = 120
        target['MaximumTestExecutionTimeAllowance'] = 180
        env = target['EnvironmentVariables']
        env['CPM_APP_INTEGRATION'] = '1'
        if flag == 'OFF':
            env['CPM_APP_INTEGRATION_DISABLE_STABLE_BASE_URL'] = '1'
        else:
            env.pop('CPM_APP_INTEGRATION_DISABLE_STABLE_BASE_URL', None)
        env['CPM_APP_INTEGRATION_RELAUNCH_PHASE'] = phase
        env['CPM_APP_INTEGRATION_RELAUNCH_TOKEN'] = token
        plan_path = products / ('P3-Relaunch-' + output.name + '-' + name + '.xctestrun')
        assert not plan_path.exists()
        plan_path.write_bytes(plistlib.dumps(plan))
        result = output / (name + '.xcresult')
        print('Starting ' + name + ' fixture=' + token, flush=True)
        with (output / (name + '.log')).open('wb') as log:
            code = subprocess.call(['xcodebuild', 'test-without-building', '-xctestrun', str(plan_path),
                                    '-destination', 'platform=macOS,arch=arm64', '-resultBundlePath', str(result)],
                                   cwd=products.parent, stdout=log, stderr=subprocess.STDOUT)
        summary = subprocess.run(['xcrun', 'xcresulttool', 'get', 'test-results', 'summary', '--path', str(result)], capture_output=True, text=True, check=True)
        (output / (name + '-summary.json')).write_text(summary.stdout)
        evidence = output / (name + '-evidence')
        subprocess.run(['xcrun', 'xcresulttool', 'export', 'attachments', '--path', str(result), '--output-path', str(evidence)], check=True, capture_output=True)
        reports = []
        for p in evidence.glob('*.json'):
            value = json.loads(p.read_text())
            if isinstance(value, dict) and 'probes' in value:
                reports.append(value)
        assert len(reports) == 1, 'Missing native test evidence'
        report = reports[0]
        observations = [x for x in report['observations'] if x.get('relaunchPhase') == phase]
        assert len(observations) == 1, 'The stage did not reach the owned relaunch checkpoint'
        observation = observations[0]
        log = (output / (name + '.log')).read_text(errors='replace')
        assert 'Owned app objects still retain' not in log
        assert 'Test timed out waiting for deallocation' not in log
        if phase == 'prepare':
            assert 'CPM APP PRESERVED RELAUNCH STORE ' + token in log
            assert 'CPM APP REMOVED PERSISTENT STORE' not in log
            previous_pid = observation['hostPID']
            assert previous_pid > 1
            deadline = time.time() + 10
            while True:
                try:
                    os.kill(previous_pid, 0)
                except ProcessLookupError:
                    break
                assert time.time() < deadline, 'The first app process did not exit; refusing to claim a relaunch'
                time.sleep(0.1)
        else:
            assert observation['previousHostPID'] == previous_pid
            assert observation['hostPID'] != previous_pid
            assert log.count('CPM APP REMOVED PERSISTENT STORE ' + token) == 1
        (output / ('bundle-after-' + name + '.json')).write_text(json.dumps(bundle(), sort_keys=True))
        s = json.loads(summary.stdout)
        results[name] = {'exit': code, 'passed': s['passedTests'], 'failed': s['failedTests'],
                         'skipped': s['skippedTests'], 'failures': s['testFailures'],
                         'fixture': token, 'observation': observation, 'probes': report['probes']}
        (output / 'results.json').write_text(json.dumps(results, indent=2))
        print(json.dumps({name: {'exit': code, 'passed': s['passedTests'], 'failed': s['failedTests'], 'skipped': s['skippedTests'], 'observation': observation}}), flush=True)
assert all((r['exit'], r['passed'], r['failed'], r['skipped']) == (0, 1, 0, 0)
           for r in results.values()), 'Relaunch acceptance failed; raw results are retained'
print('RELAUNCH COMPLETE', flush=True)
